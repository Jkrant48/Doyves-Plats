DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1
    FROM pg_type
    WHERE typnamespace = 'public'::regnamespace
      AND typname = 'account_type'
  ) THEN
    CREATE TYPE public.account_type AS ENUM (
      'Customer',
      'Management',
      'Admin',
      'Employee'
    );
  END IF;
END
$$;

CREATE TABLE IF NOT EXISTS public.users (
  users_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_role public.account_type NOT NULL DEFAULT 'Customer',
  user_email VARCHAR(255) NOT NULL UNIQUE,
  user_password_hash VARCHAR(255) NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

UPDATE public.users
SET user_role = 'Admin'
WHERE user_role = 'Management';

CREATE TABLE IF NOT EXISTS public.category (
  category_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category_name VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS public.services (
  services_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  service_name VARCHAR(150) NOT NULL,
  service_description TEXT,
  service_price NUMERIC(10, 2) NOT NULL,
  deposit_amount NUMERIC(10, 2) NOT NULL,
  duration_minutes INT NOT NULL,
  category_id INT NOT NULL,
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  CONSTRAINT services_category_fk
    FOREIGN KEY (category_id)
    REFERENCES public.category(category_id)
    ON UPDATE CASCADE
    ON DELETE RESTRICT,
  CONSTRAINT service_price_check CHECK (service_price > 0),
  CONSTRAINT deposit_amount_check
    CHECK (deposit_amount >= 0 AND deposit_amount <= service_price),
  CONSTRAINT duration_check CHECK (duration_minutes > 0)
);

CREATE TABLE IF NOT EXISTS public.appointments (
  appointments_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_name VARCHAR(255) NOT NULL,
  customer_email VARCHAR(255) NOT NULL,
  customer_phone VARCHAR(20) NOT NULL,
  service_id INT NOT NULL,
  appointment_datetime TIMESTAMP NOT NULL,
  service_price NUMERIC(10, 2) NOT NULL,
  deposit_amount NUMERIC(10, 2) NOT NULL,
  appointment_status VARCHAR(30) NOT NULL DEFAULT 'pending_payment',
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  stripe_checkout_session_id TEXT,
  CONSTRAINT appointments_service_fk
    FOREIGN KEY (service_id)
    REFERENCES public.services(services_id)
    ON UPDATE CASCADE
    ON DELETE RESTRICT,
  CONSTRAINT appointment_price_check CHECK (service_price >= 0),
  CONSTRAINT appointment_deposit_check
    CHECK (deposit_amount >= 0),
  CONSTRAINT appointment_status_check
    CHECK (appointment_status IN (
      'pending_payment',
      'confirmed',
      'completed',
      'missed',
      'cancelled',
      'no_show',
      'checkout_failed',
      'payment_failed',
      'payment_expired'
    ))
);

CREATE UNIQUE INDEX IF NOT EXISTS appointments_stripe_checkout_session_id_unique
  ON public.appointments (stripe_checkout_session_id)
  WHERE stripe_checkout_session_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_appointments_datetime
  ON public.appointments (appointment_datetime);
CREATE INDEX IF NOT EXISTS idx_appointments_status
  ON public.appointments (appointment_status);

CREATE TABLE IF NOT EXISTS public.appointment_add_ons (
  appointment_id INT NOT NULL,
  service_id INT NOT NULL,
  service_price NUMERIC(10, 2) NOT NULL,
  deposit_amount NUMERIC(10, 2) NOT NULL,
  PRIMARY KEY (appointment_id, service_id),
  CONSTRAINT appointment_add_ons_appointment_fk
    FOREIGN KEY (appointment_id)
    REFERENCES public.appointments(appointments_id)
    ON DELETE CASCADE,
  CONSTRAINT appointment_add_ons_service_fk
    FOREIGN KEY (service_id)
    REFERENCES public.services(services_id)
    ON UPDATE CASCADE
    ON DELETE RESTRICT,
  CONSTRAINT appointment_add_ons_price_check CHECK (service_price >= 0),
  CONSTRAINT appointment_add_ons_deposit_check
    CHECK (deposit_amount >= 0 AND deposit_amount <= service_price)
);

CREATE TABLE IF NOT EXISTS public.payments (
  payment_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  appointment_id INT NOT NULL,
  amount NUMERIC(10, 2) NOT NULL,
  currency VARCHAR(3) NOT NULL DEFAULT 'EUR',
  payment_reference VARCHAR(255) NOT NULL UNIQUE,
  payment_status VARCHAR(30) NOT NULL DEFAULT 'pending',
  payment_method VARCHAR(50),
  paid_at TIMESTAMP,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT payments_appointment_fk
    FOREIGN KEY (appointment_id)
    REFERENCES public.appointments(appointments_id)
    ON UPDATE CASCADE
    ON DELETE RESTRICT,
  CONSTRAINT payment_amount_check CHECK (amount > 0),
  CONSTRAINT payment_status_check
    CHECK (payment_status IN ('pending', 'successful', 'failed', 'refunded'))
);
CREATE INDEX IF NOT EXISTS idx_payments_appointment
  ON public.payments (appointment_id);
CREATE INDEX IF NOT EXISTS idx_payments_status
  ON public.payments (payment_status);

CREATE TABLE IF NOT EXISTS public.portfolio_images (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  image_url VARCHAR(2048) NOT NULL,
  alt_text VARCHAR(200) NOT NULL DEFAULT '',
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  portfolio_title VARCHAR(100) NOT NULL,
  portfolio_description TEXT,
  services_id INT NOT NULL,
  storage_path TEXT,
  CONSTRAINT portfolio_images_service_fk
    FOREIGN KEY (services_id)
    REFERENCES public.services(services_id)
    ON UPDATE CASCADE
    ON DELETE RESTRICT
);
CREATE INDEX IF NOT EXISTS idx_portfolio_images_service
  ON public.portfolio_images (services_id);
