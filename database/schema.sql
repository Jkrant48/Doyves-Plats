ALTER TABLE public.portfolio_images
  ADD COLUMN IF NOT EXISTS services_id INT;
ALTER TABLE public.portfolio_images
  ADD COLUMN IF NOT EXISTS storage_path TEXT;

UPDATE public.portfolio_images
SET portfolio_title = COALESCE(NULLIF(BTRIM(portfolio_title), ''), NULLIF(BTRIM(alt_text), ''), 'Portfolio image')
WHERE portfolio_title IS NULL OR BTRIM(portfolio_title) = '';

DO $$
BEGIN
  IF EXISTS (
    SELECT 1
    FROM public.portfolio_images
    WHERE services_id IS NULL
  ) THEN
    RAISE EXCEPTION
      'Every portfolio image must be linked to a service. Set services_id for existing portfolio_images rows, then rerun the schema.';
  END IF;
END
$$;

