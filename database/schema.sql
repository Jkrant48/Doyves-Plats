  ALTER COLUMN portfolio_title SET NOT NULL,
  ALTER COLUMN services_id SET NOT NULL;
ALTER TABLE public.portfolio_images
  DROP CONSTRAINT IF EXISTS portfolio_images_services_id_fkey;
ALTER TABLE public.portfolio_images
  DROP CONSTRAINT IF EXISTS portfolio_images_service_fk;
ALTER TABLE public.portfolio_images
  ADD CONSTRAINT portfolio_images_service_fk
  FOREIGN KEY (services_id)
  REFERENCES public.services(services_id)
  ON UPDATE CASCADE
  ON DELETE RESTRICT;

CREATE TABLE IF NOT EXISTS public.reviews (
  reviews_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  appointment_id INT NOT NULL,
  user_id INT,
  review_rating SMALLINT NOT NULL,
  review_text TEXT,
  review_author VARCHAR(255) NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  is_approved BOOLEAN NOT NULL DEFAULT FALSE,
  CONSTRAINT reviews_appointment_fk
    FOREIGN KEY (appointment_id)
    REFERENCES public.appointments(appointments_id)
    ON UPDATE CASCADE
    ON DELETE CASCADE,
  CONSTRAINT reviews_user_fk
    FOREIGN KEY (user_id)
    REFERENCES public.users(users_id)
    ON UPDATE CASCADE
    ON DELETE SET NULL,
  CONSTRAINT review_rating_check CHECK (review_rating BETWEEN 1 AND 5)
);

ALTER TABLE public.reviews
  ADD COLUMN IF NOT EXISTS appointment_id INT;
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1
    FROM pg_constraint
    WHERE conname = 'reviews_appointment_fk'
      AND conrelid = 'public.reviews'::regclass
  ) THEN
    ALTER TABLE public.reviews
      ADD CONSTRAINT reviews_appointment_fk
      FOREIGN KEY (appointment_id)
      REFERENCES public.appointments(appointments_id)
      ON UPDATE CASCADE
      ON DELETE CASCADE;
  END IF;
END
$$;
CREATE UNIQUE INDEX IF NOT EXISTS reviews_appointment_id_unique
  ON public.reviews (appointment_id)
  WHERE appointment_id IS NOT NULL;

CREATE TABLE IF NOT EXISTS public.messages (
  message_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_name VARCHAR(255) NOT NULL,
  customer_email VARCHAR(255) NOT NULL,
  message_text TEXT NOT NULL,
  is_read BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

COMMIT;
